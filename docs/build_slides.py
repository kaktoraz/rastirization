def title_bar(s, text, sub=None):
    bar = s.shapes.add_shape(1, 0, 0, prs.slide_width, Inches(1.0))
    bar.fill.solid(); bar.fill.fore_color.rgb = NAVY; bar.line.fill.background()
    tf = bar.text_frame; tf.margin_left = Inches(0.5); tf.margin_top = Inches(0.1)
    tf.vertical_anchor = MSO_ANCHOR.MIDDLE
    p = tf.paragraphs[0]; p.text = text
    p.font.size = Pt(28); p.font.bold = True; p.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
    p.font.name = "Calibri"
    if sub:
        p2 = tf.add_paragraph(); p2.text = sub
        p2.font.size = Pt(14); p2.font.color.rgb = RGBColor(0xC9, 0xD6, 0xE8)

def textbox(s, x, y, w, h, items, size=18, color=GREY, bullet_char="•", spacing=8):
    tb = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame; tf.word_wrap = True
    first = True
    for it in items:
        if isinstance(it, tuple):
            text, opts = it
        else:
            text, opts = it, {}
        p = tf.paragraphs[0] if first else tf.add_paragraph()
        first = False
        sz = opts.get("size", size)
        col = opts.get("color", color)
        bold = opts.get("bold", False)
        prefix = opts.get("bullet", bullet_char)
        if opts.get("no_bullet"):
            p.text = text
        else:
            p.text = f"{prefix} {text}" if prefix else text
        p.font.size = Pt(sz); p.font.color.rgb = col; p.font.bold = bold
        p.font.name = "Calibri"
        p.space_after = Pt(spacing)
        if opts.get("center"):
            p.alignment = PP_ALIGN.CENTER
    return tb

def formula(s, x, y, w, text, size=20, color=NAVY, h=0.6):
    tb = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame; tf.word_wrap = True
    p = tf.paragraphs[0]; p.text = text; p.alignment = PP_ALIGN.CENTER
    p.font.size = Pt(size); p.font.italic = True; p.font.color.rgb = color; p.font.name = "Cambria"
    return tb

def notes(s, text):
    s.notes_slide.notes_text_frame.text = text

def picture(s, fname, x, y, w):
    s.shapes.add_picture(os.path.join(PLOTS, fname), Inches(x), Inches(y), width=Inches(w))

def make_table(s, x, y, w, h, data, font=13, col_widths=None, highlight_rows=()):
    rows, cols = len(data), len(data[0])
    gt = s.shapes.add_table(rows, cols, Inches(x), Inches(y), Inches(w), Inches(h)).table
    if col_widths:
        total = sum(col_widths)
        for i, cw in enumerate(col_widths):
            gt.columns[i].width = Emu(int(Inches(w) * cw / total))
    for r in range(rows):
        for c in range(cols):
            cell = gt.cell(r, c)
            cell.text = str(data[r][c])
            for p in cell.text_frame.paragraphs:
                p.font.size = Pt(font)
                p.font.name = "Calibri"
                p.alignment = PP_ALIGN.LEFT if c == 0 else PP_ALIGN.CENTER
                p.font.bold = (r == 0) or (r in highlight_rows)
                p.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF) if r == 0 else (RED if r in highlight_rows else GREY)
            cell.margin_left = Inches(0.06); cell.margin_right = Inches(0.04)
            cell.margin_top = Inches(0.01); cell.margin_bottom = Inches(0.01)
    return gt

