#!/usr/bin/env bash
# ===================================================================
#  Сглаживание изображений (проект АКСФ) — запуск в один клик
#  Linux / macOS:  bash запустить_сглаживание.sh
#  Что делает: собирает программу, обрабатывает ВСЕ картинки из
#  папки my_images всеми методами и складывает результаты в my_results
# ===================================================================
set -e
cd "$(dirname "$0")"

echo "============================================================"
echo "  Сглаживание изображений: адаптивный контрастно-структурный"
echo "  фильтр (АКСФ) — учебный проект"
echo "============================================================"
echo

if ! command -v cargo >/dev/null 2>&1; then
    echo "[!] Не найден Rust (команда cargo)."
    echo "    Установите его один раз командой:"
    echo "      curl --proto '=https' --tlsv1.2 -sSf https://sh.rustup.rs | sh"
    echo "    затем перезапустите этот скрипт."
    exit 1
fi

echo "[1/3] Сборка программы (первый раз может занять 1–2 минуты)..."
cargo build --release

mkdir -p my_images my_results

echo
echo "[2/3] Обрабатываю картинки из папки my_images ..."
echo "      (положите туда свои фото в формате jpg/png и запустите снова)"
echo
./target/release/smoothing_project demo -d my_images -o my_results --rgb --sigma 25

echo
echo "[3/3] Готово! Результаты в папке my_results"
echo
echo "Подсказка: файл с окончанием _1_acsf.png — это результат НАШЕГО метода."
echo "Чтобы изменить уровень шума, откройте этот файл в текстовом редакторе"
echo "и замените --sigma 25 на, например, --sigma 10 или --sigma 40."
